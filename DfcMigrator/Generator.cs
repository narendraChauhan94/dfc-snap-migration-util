using System.Net;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;
using System.Xml.Linq;

namespace DfcMigrator;

public record OutputFile(string RelPath, byte[] Content, string Action, string Source);

public class GenerationResult
{
    public List<OutputFile> Files { get; } = [];
    public List<string> Skipped { get; } = [];
    public List<string> Errors { get; } = [];
    public List<string> Warnings { get; } = [];
    public bool IsValid => Errors.Count == 0;
}

public class TemplateException(string message) : Exception(message);

// Clones the common template (Template\GenericClubFastDD) and fills it from the plan, in memory.
// Nothing touches disk here, so the dry run and the real run execute exactly the same code.
public static class SiteGenerator
{
    const string Token = "GenericClub";
    const string PageTemplate = "GenericClub"; // Web Sales AND Internal pages use it (proven manual process)
    const string DefaultLogo = "Images/Xplor_Pay_Logo_White.png";
    const string BranchViewsSlot = "<!-- BRANCH VIEWS: generated by dfcmigrate -->";
    static readonly UTF8Encoding Utf8NoBom = new(false);

    // Template files that are not part of a migrated site.
    static readonly Dictionary<string, string> NotCopied = new(StringComparer.OrdinalIgnoreCase)
    {
        ["GenericClubInClub.aspx"] = "old in-club page (Internal pages now use the web page, as in the reference client)",
        ["GenericClubInClub.config"] = "config of the old in-club page",
        ["GenericClubSnapDDASignup.aspx"] = "legacy V5 page",
        ["GenericClubSnapDDASignup.config"] = "config of the legacy V5 page",
    };

    public static GenerationResult Generate(SitePlan site, string templateDir)
    {
        var r = new GenerationResult();
        if (!Directory.Exists(templateDir)) { r.Errors.Add($"Template folder not found: {templateDir}"); return r; }
        string aspxPath = Path.Combine(templateDir, PageTemplate + ".aspx"), configPath = Path.Combine(templateDir, PageTemplate + ".config");
        if (!File.Exists(aspxPath) || !File.Exists(configPath)) { r.Errors.Add($"Template is missing {PageTemplate}.aspx/.config."); return r; }

        string? logoRel = site.LogoFile is null ? null : "Images/" + Path.GetFileName(site.LogoFile);
        if (site.LogoFile is not null) r.Files.Add(new(logoRel!, File.ReadAllBytes(site.LogoFile), "Added", Path.GetFileName(site.LogoFile)));
        else r.Warnings.Add($"No logo supplied - pages keep {DefaultLogo}.");

        try
        {
            // One page file shared by all pages (the reference's Web and Internal .aspx are identical).
            var aspx = BuildAspx(File.ReadAllText(aspxPath), site, logoRel);
            var configTemplate = File.ReadAllText(configPath);
            foreach (var page in site.Pages)
            {
                r.Files.Add(new($"{page.PageName}.aspx", Utf8NoBom.GetBytes(aspx), "Renamed+Modified", PageTemplate + ".aspx"));
                r.Files.Add(new($"{page.PageName}.config", Utf8NoBom.GetBytes(BuildConfig(configTemplate, page, site)), "Renamed+Modified", PageTemplate + ".config"));
            }
        }
        catch (TemplateException ex) { r.Errors.Add("Template: " + ex.Message); return r; }

        foreach (var full in Directory.EnumerateFiles(templateDir, "*", SearchOption.AllDirectories).Order())
        {
            string rel = Path.GetRelativePath(templateDir, full).Replace('\\', '/');
            string name = Path.GetFileName(rel);
            if (!rel.Contains('/') && NotCopied.TryGetValue(name, out var why)) { r.Skipped.Add($"{rel} - {why}"); continue; }
            if (rel.Equals(PageTemplate + ".aspx", StringComparison.OrdinalIgnoreCase) || rel.Equals(PageTemplate + ".config", StringComparison.OrdinalIgnoreCase)) continue;
            if (name.Equals("ClubStyle.css", StringComparison.OrdinalIgnoreCase))
            {
                r.Files.Add(new(rel, Utf8NoBom.GetBytes(FillColours(File.ReadAllText(full), site.Colours)), "Modified", rel));
                continue;
            }
            if (rel.StartsWith("Emails/", StringComparison.OrdinalIgnoreCase) && name.StartsWith(Token, StringComparison.Ordinal))
            {
                r.Files.Add(new($"Emails/{site.Folder}{name[Token.Length..]}", File.ReadAllBytes(full), "Renamed", rel));
                continue;
            }
            r.Files.Add(new(rel, File.ReadAllBytes(full), "Copied", rel));
        }
        if (r.IsValid) VerifyOutput(r, site.Folder);
        return r;
    }

    // ------------------------------------------------------------------ config

    static string BuildConfig(string xml, PagePlan page, SitePlan site)
    {
        string nl = xml.Contains("\r\n") ? "\r\n" : "\n";
        XDocument doc;
        try { doc = XDocument.Parse(xml); } catch (XmlException ex) { throw new TemplateException($"config is not valid XML: {ex.Message}"); }
        var root = doc.Root!;
        var g = Required(root, "GlobalSettings");

        // The template's annotation comments (disabled member-email settings etc.) carry the customer's names, as in the reference.
        foreach (var c in doc.DescendantNodes().OfType<XComment>())
            c.Value = c.Value.Replace("Generic Club", site.CustomerName).Replace(Token, site.Folder);

        SetText(Required(g, "LogMessagePrefix"), $"/Clients/{site.Folder}/{page.PageName}.aspx");
        foreach (var (key, v) in site.Globals[page.Portal.Id])
        {
            var e = Required(g, key);
            SetText(e, v.Value);
            if (v.Note is not null) e.Add(new XComment($" {v.Note} "));
        }

        // Products: every plan of every branch, cloned from the template product of the same kind.
        var products = Required(root, "Products");
        var bases = products.Elements("Product").ToDictionary(e => (string?)e.Attribute("ID") ?? "");
        if (!bases.ContainsKey("monthly_product") || !bases.ContainsKey("oneoff_product"))
            throw new TemplateException("config must contain <Product ID=\"monthly_product\"> and <Product ID=\"oneoff_product\">");
        products.RemoveNodes();
        var ordered = page.Branches.SelectMany(b => b.Products)
            .OrderBy(p => p.CategorySort).ThenBy(p => p.CategoryName, StringComparer.Ordinal).ThenBy(p => p.ClubRef, StringComparer.Ordinal).ThenBy(p => p.Name, StringComparer.Ordinal);
        foreach (var p in ordered) products.Add(BuildProduct(new XElement(bases[p.OneOff ? "oneoff_product" : "monthly_product"]), p, page));

        // Branches: one per migrated venue, cloned from the template branch.
        var branches = Required(root, "Branches");
        var baseBranch = branches.Element("Branch") ?? throw new TemplateException("config has no <Branch> to clone");
        branches.RemoveNodes();
        foreach (var b in page.Branches.OrderBy(b => b.Id, StringComparer.Ordinal))
        {
            var e = new XElement(baseBranch);
            e.SetAttributeValue("ID", b.Id);
            SetText(Required(e, "MerchantID"), b.MerchantId);
            SetText(Required(e, "DDMS_Beneficiary"), b.BeneficiaryId);
            SetText(Required(e, "Description"), b.Venue.Name);
            var emails = Required(e, "ConfirmationEmail_Branch_EmailAddresses");
            SetText(emails, b.NotifyEmails);
            e.Element("ProductPageBranchInfo")?.Remove();
            if (b.Venue.Welcome != "") emails.AddAfterSelf(new XElement("ProductPageBranchInfo", HtmlFix.Balance(b.Venue.Welcome, out _, out _) ?? ""));
            var ids = Required(e, "ProductIDs");
            ids.RemoveNodes();
            foreach (var p in b.Products.OrderBy(p => p.Id, StringComparer.Ordinal)) ids.Add(new XElement("item", p.Id));
            branches.Add(e);
        }

        var sb = new StringBuilder();
        using (var w = XmlWriter.Create(sb, new XmlWriterSettings { Indent = true, IndentChars = "  ", OmitXmlDeclaration = true }))
            doc.Save(w);
        return ("<?xml version=\"1.0\"?>\n" + sb + "\n").Replace("\r\n", "\n").Replace("\n", nl);
    }

    static XElement BuildProduct(XElement e, ProductPlan p, PagePlan page)
    {
        e.SetAttributeValue("ID", p.Id);
        SetText(Required(e, "ProductDescription"), p.Name);
        SetText(Required(e, "ProductDescriptionLong"), p.Name);
        SetText(Required(e, "ProductDescriptionLongHTML"), p.DescriptionHtml);
        SetText(Required(e, "MonthlyMembershipFeePence"), p.FeePence.ToString());
        SetText(Required(e, "JoiningFeePence"), p.JoinFeePence.ToString());
        SetText(Required(e, "ContractLengthMonths"), p.ContractMonths.ToString());
        SetText(Required(e, "YoungAgeLimitYears"), p.MinAge.ToString());
        var days = Required(e, "CollectionScheduleDaysOfMonth");
        days.RemoveNodes();
        foreach (var d in page.CollectionDays) days.Add(new XElement("item", d));
        if (p.OneOff) SetText(Required(e, "OneOffMembershipDuration"), p.OneOffMonths!.Value.ToString());
        return e;
    }

    static XElement Required(XElement parent, string name) =>
        parent.Element(name) ?? throw new TemplateException($"<{parent.Name}> has no <{name}>");

    static void SetText(XElement e, string value) { e.RemoveNodes(); e.Value = value; }

    // ------------------------------------------------------------------ aspx

    static string BuildAspx(string aspx, SitePlan site, string? logoRel)
    {
        string nl = aspx.Contains("\r\n") ? "\r\n" : "\n";
        int slot = UniqueIndex(aspx, BranchViewsSlot);
        int lineStart = aspx.LastIndexOf('\n', slot) + 1;
        string indent = aspx[lineStart..slot];

        // Branch information panels (SnapSignup.vb shows the View whose ID = selected BranchID; the first View is the default).
        var controlIds = Regex.Matches(aspx, "\\bID=\"([^\"]+)\"", RegexOptions.IgnoreCase).Select(m => m.Groups[1].Value).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var branches = site.Pages.SelectMany(p => p.Branches).GroupBy(b => b.Id).OrderBy(g => g.Key, StringComparer.Ordinal).Select(g => g.First()).ToList();
        var clash = branches.FirstOrDefault(b => controlIds.Contains(b.Id));
        if (clash is not null) throw new TemplateException($"branch id '{clash.Id}' clashes with an existing control ID on the page");

        var clubEmail = site.WebClub.Email != "" ? site.WebClub.Email : site.WebClub.NotifyEmail;
        var views = new List<string> { View(indent, nl, "GenericBranchInfo",
            [$"<p><strong>{H(site.CustomerName)}</strong></p>", "<p>Select a venue above to see its address and contact details.</p>", EmailLine(clubEmail)]) };
        foreach (var b in branches)
        {
            // The first address line is dropped when the venue name already starts with it (reference panels).
            var lines = b.Venue.AddressLines.SkipWhile(l => b.Venue.Name.StartsWith(l, StringComparison.OrdinalIgnoreCase));
            var body = new List<string> { $"<p><strong>{H(b.Venue.Name)}</strong>{string.Concat(lines.Select(a => "<br />" + H(a)))}</p>" };
            if (b.Venue.Telephone != "") body.Add($"<p><strong>Phone:</strong><br />{H(b.Venue.Telephone)}</p>");
            if (b.Venue.DisplayEmail != "") body.Add(EmailLine(b.Venue.DisplayEmail));
            views.Add(View(indent, nl, b.Id, body));
        }
        aspx = aspx[..lineStart] + string.Join(nl, views) + aspx[(slot + BranchViewsSlot.Length)..];

        if (logoRel is not null)
        {
            UniqueIndex(aspx, $"src=\"{DefaultLogo}\"");
            aspx = aspx.Replace($"src=\"{DefaultLogo}\"", $"src=\"Images/{Uri.EscapeDataString(logoRel[7..])}\"");
        }
        return aspx;
    }

    static string View(string indent, string nl, string id, IEnumerable<string> body)
    {
        var l = new List<string>
        {
            $"{indent}<asp:View ID=\"{id}\" runat=\"server\" EnableViewState=\"false\">",
            $"{indent}\t<div class=\"BranchInfoHeader\">", $"{indent}\t\t<h2>Club Information</h2>", $"{indent}\t</div>",
            $"{indent}\t<div class=\"SnapInfoBody\">",
        };
        l.AddRange(body.Where(x => x != "").Select(x => $"{indent}\t\t{x}"));
        l.Add($"{indent}\t</div>");
        l.Add($"{indent}</asp:View>");
        return string.Join(nl, l);
    }

    static string EmailLine(string email) =>
        email == "" ? "" : $"<p><strong>Email:</strong><br /><a href=\"mailto:{H(email)}\">{H(email)}</a></p>";

    static string H(string s) => WebUtility.HtmlEncode(s.Replace('\r', ' ').Replace('\n', ' '));

    static int UniqueIndex(string text, string marker)
    {
        int i = text.IndexOf(marker, StringComparison.Ordinal);
        if (i < 0) throw new TemplateException($"marker not found: {marker}");
        if (text.IndexOf(marker, i + marker.Length, StringComparison.Ordinal) >= 0) throw new TemplateException($"marker appears more than once: {marker}");
        return i;
    }

    // ------------------------------------------------------------------ stylesheet

    static string FillColours(string css, Dictionary<string, string> colours)
    {
        foreach (var (name, hex) in colours) css = css.Replace("{{" + name + "}}", hex);
        return css;
    }

    // ------------------------------------------------------------------ safety net

    // Never emit a half-customised site: no template names/markers/tokens, no dangling /Clients/<site>/ or Images/ references.
    /// <summary>The file without comments: XML/HTML &lt;!-- --&gt;, ASP.NET &lt;%-- --%&gt;, CSS /* */ and VB ' lines.</summary>
    public static string LiveContent(string text, string file)
    {
        text = Regex.Replace(text, "<!--.*?-->|<%--.*?--%>", "", RegexOptions.Singleline);
        if (file.EndsWith(".css", StringComparison.OrdinalIgnoreCase)) text = Regex.Replace(text, @"/\*.*?\*/", "", RegexOptions.Singleline);
        if (file.EndsWith(".aspx", StringComparison.OrdinalIgnoreCase)) text = Regex.Replace(text, @"^[ \t]*'.*$", "", RegexOptions.Multiline);
        return text;
    }

    static void VerifyOutput(GenerationResult r, string site)
    {
        var paths = r.Files.Select(f => f.RelPath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        // Files the site actually loads (ClubStyle_backup.css is copied unchanged and never referenced, as in the reference).
        foreach (var f in r.Files.Where(f => f.RelPath.EndsWith(".aspx") || f.RelPath.EndsWith(".config") || f.RelPath.Equals("ClubStyle.css", StringComparison.OrdinalIgnoreCase)))
        {
            var raw = Encoding.UTF8.GetString(f.Content);
            foreach (var bad in new[] { "<!-- REPLACE -->", "<!-- Club ID -->", BranchViewsSlot })
                if (raw.Contains(bad, StringComparison.OrdinalIgnoreCase)) r.Errors.Add($"{f.RelPath}: still contains template marker '{bad}'.");
            var text = LiveContent(raw, f.RelPath); // comments are documentation (the reference keeps some old names in them)
            foreach (var bad in new[] { Token, "Generic Club", "{{" })
                if (text.Contains(bad, StringComparison.OrdinalIgnoreCase))
                    r.Errors.Add($"{f.RelPath}: still contains template marker '{bad}'.");
            foreach (Match m in Regex.Matches(text, $"/Clients/{site}/([^<\"'\\s]+)", RegexOptions.IgnoreCase))
                if (!paths.Contains(m.Groups[1].Value))
                    r.Errors.Add($"{f.RelPath}: references /Clients/{site}/{m.Groups[1].Value} which is not in the generated site.");
            if (f.RelPath.EndsWith(".aspx"))
                foreach (Match m in Regex.Matches(text, "src=\"(Images/[^\"]+)\""))
                    if (!paths.Contains(Uri.UnescapeDataString(m.Groups[1].Value)))
                        r.Errors.Add($"{f.RelPath}: image {m.Groups[1].Value} is not in the generated site.");
        }
    }
}
